def set_dotted(root, path, value):
    """Set value at dotted path (e.g. 'a.b.c' -> root['a']['b']['c'] = value)."""
    parts = path.split('.')
    curr = root
    for part in parts[:-1]:
        if part not in curr or not isinstance(curr[part], dict):
            curr[part] = {}
        curr = curr[part]
    curr[parts[-1]] = value

def main():
    print("Starting locale translation backfill...")
    
    for lang in LOCALES:
        json_path = LOCALES_DIR / f"{lang}.json"
        if not json_path.exists():
            print(f"Skipping {lang} (file not found: {json_path})")
            continue
            
        try:
            # BOM-tolerant read
            content_text = json_path.read_text(encoding="utf-8-sig")
            data = json.loads(content_text)
            
            lang_dict = TRANSLATIONS.get(lang, {})
            if not lang_dict:
                print(f"No translations for {lang}, skipping.")
                continue
                
            print(f"Merging {len(lang_dict)} keys into {lang}.json...")
            for key, val in lang_dict.items():
                set_dotted(data, key, val)
                
            # Pretty-print with 2 spaces indent, preserve non-ascii, add trailing newline
            output_text = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
            json_path.write_text(output_text, encoding="utf-8")
            print(f"Successfully updated {lang}.json")
            
        except Exception as e:
            print(f"Error updating {lang}.json: {e}")

if __name__ == "__main__":
    main()
